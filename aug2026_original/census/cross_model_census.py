# -*- coding: utf-8 -*-
"""
Multi-model census validity test. FIVE diverse LLM raters from four families
(two Anthropic Claude models via API + Qwen + Llama + Mistral via Ollama) independently
apply the provenance-circularity rubric to each benchmark's construction
description and assign a 0-4 bin. We then measure cross-model agreement
(Krippendorff alpha) and each model's agreement with the locked census, to test
whether the rubric measures a property reproducible across model families rather
than an artifact of two co-instructed Claude raters.

ASCII-only output. Run from the extracted archive root:
    python census/cross_model_census.py
Requires ANTHROPIC_API_KEY in .env and a running Ollama daemon.
"""
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

PACKAGE_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_JSON = Path(__file__).resolve().with_name("cross_model_census_raw.json")

# --- load ANTHROPIC_API_KEY from .env without printing it ---
def load_env_key():
    envp = PACKAGE_ROOT / ".env"
    if envp.exists():
        for line in envp.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = line.strip()
            if line.startswith("ANTHROPIC_API_KEY"):
                return line.split("=", 1)[1].strip().strip('"').strip("'")
    return os.environ.get("ANTHROPIC_API_KEY")

# --- census items: (name, construction description, reference bin) ---
ITEMS = [
    ("MuSiQue", "Bottom-up from human-annotated single-hop questions; the supporting paragraph is the annotated long answer carried over from the source datasets. No knowledge graph is used. Disconnection and anti-leakage filters are applied.", 0),
    ("HotpotQA", "Crowdworkers write questions over two linked Wikipedia paragraphs and mark sentence-level supporting facts by hand. The paper explicitly rejects a knowledge graph and focuses on text-based QA.", 0),
    ("MultiHop-RAG", "Factual sentences are extracted from news articles by a trained classifier; the gold evidence is these source-text sentences. Questions are generated by an LLM from text claims. No knowledge graph is used.", 0),
    ("Natural Questions", "Annotators are shown a question with a Wikipedia page from the top search results and select the smallest HTML bounding box that contains the answer as the long answer, and a span on that page as the short answer.", 1),
    ("GRADE", "Shortest directed acyclic paths of length 2 to 5 are enumerated within a knowledge graph; the answer is the terminal node and all supporting facts are contained in the edge set. Semantic-clustering augmentation adds links; retrieval chunks trace to source documents.", 3),
    ("STaRK", "A relation template is sampled and instantiated into a relational requirement over a knowledge base; the gold answer is the KB node satisfying that requirement. Three models verify the gold answer set.", 3),
    ("TriviaQA", "Questions and answers are authored independently by trivia enthusiasts; evidence documents are retained for a question only when they contain the answer string (distant supervision).", 3),
    ("GraphRAG-Bench", "Logic Mining transforms raw text into structured ontologies and subgraphs; questions are generated anchored to a structured evidence subgraph mined from the corpus, with human checking.", 3),
    ("2WikiMultiHop", "Evidence is a set of triples (subject entity, property, object entity) obtained from Wikidata; questions are created from predefined templates using logical-rule information in the knowledge graph.", 4),
    ("MetaQA", "All questions are generated from a movie knowledge base; the answer is the tail entity reached by knowledge-graph path traversal, with 2-hop and 3-hop questions generated from the same knowledge base.", 4),
    ("WebQSP", "SPARQL queries with standard Freebase entity identifiers are provided and are directly executable on Freebase; the gold answers are the Freebase entities returned by executing the parse.", 4),
    ("Ours-upper-anchor", "Gold entity, edge, and path are copied directly from the evaluation knowledge graph by construction; no LLM is involved in producing these gold fields.", 4),
    ("Ours-lower-anchor", "The answer and evidence are derived only from passage text; the knowledge graph is never provided in the generation prompt, enforced by a static import guard.", 0),
]

RUBRIC = (
    "You are scoring how a question-answering benchmark's retrieval GOLD was constructed, "
    "on a five-level provenance-circularity scale. K = the evaluation knowledge graph or base "
    "that a graph retriever ranks over. A = the answer surface, the spans where the answer string appears.\n"
    "bin 0: human or source-text gold, independent of K and A.\n"
    "bin 1: human or text gold with KG-guided or answer-guided selection.\n"
    "bin 2: auto-generated and then human-validated.\n"
    "bin 3: auto-generated from KG triples or templates, OR evidence retained by answer-string distant supervision.\n"
    "bin 4: gold copied directly from the evaluation KG, OR selected solely because it contains the answer string.\n"
)

def make_prompt(name, desc):
    return (RUBRIC + "\nBenchmark: " + name + "\nHow its gold was constructed: " + desc +
            "\n\nReply with ONLY one integer from 0 to 4 (the bin). No other text.")

def parse_bin(text):
    m = re.search(r"[0-4]", text or "")
    return int(m.group(0)) if m else None

# --- Ollama ---
def ollama_bin(model, prompt):
    body = json.dumps({"model": model, "prompt": prompt, "stream": False,
                       "options": {"temperature": 0.0, "num_predict": 8}}).encode()
    req = urllib.request.Request("http://localhost:11434/api/generate", data=body,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=180) as r:
        out = json.loads(r.read().decode())
    return parse_bin(out.get("response", ""))

# --- Claude ---
def claude_bin(client, model, prompt):
    # NB: Opus 4.8 deprecates the temperature parameter; omit it for all Claude models.
    msg = client.messages.create(model=model, max_tokens=16,
                                 messages=[{"role": "user", "content": prompt}])
    text = ""
    for block in msg.content:
        if getattr(block, "type", None) == "text":
            text += getattr(block, "text", "") or ""
    return parse_bin(text)

def main():
    raters = {}  # name -> dict(item_name -> bin)
    # Claude
    key = load_env_key()
    claude_model = None
    if key:
        try:
            import anthropic
            client = anthropic.Anthropic(api_key=key)
            # candidate model id -> list of fallback aliases
            claude_targets = [
                ("opus-4.8", ("claude-opus-4-8",)),
                ("sonnet-4.5", ("claude-sonnet-4-5",)),
            ]
            for label, cands in claude_targets:
                model = None
                for cand in cands:
                    try:
                        _ = claude_bin(client, cand, "Reply with 0")
                        model = cand
                        break
                    except Exception:
                        continue
                if not model:
                    print("claude: no working model for", label, flush=True)
                    continue
                bins = {}
                for name, desc, _ref in ITEMS:
                    bins[name] = claude_bin(client, model, make_prompt(name, desc))
                raters["claude:" + model] = bins
                print("claude model used:", model, flush=True)
        except Exception as e:
            print("claude error:", repr(e)[:200], flush=True)
    else:
        print("no ANTHROPIC_API_KEY found", flush=True)
    # Ollama models
    for model in ("qwen2.5:14b", "llama3.1:8b", "mistral-small:24b"):
        try:
            bins = {}
            for name, desc, _ref in ITEMS:
                bins[name] = ollama_bin(model, make_prompt(name, desc))
            raters[model] = bins
            print("ollama done:", model, flush=True)
        except Exception as e:
            print("ollama error", model, repr(e)[:160], flush=True)
    # save raw
    out = {"items": [{"name": n, "ref": r} for n, _d, r in ITEMS], "raters": raters}
    p = OUTPUT_JSON
    # Never clobber the frozen 5-rater matrix shipped with the archive: a rerun
    # (e.g. without ANTHROPIC_API_KEY it would produce a 3-rater file) is
    # diverted to a sibling .rerun.json when the frozen file already exists.
    if p.exists():
        p = p.with_name("cross_model_census_raw.rerun.json")
        print("frozen cross_model_census_raw.json preserved; writing rerun to", p, flush=True)
    p.parent.mkdir(parents=True, exist_ok=True)
    json.dump(out, open(p, "w", encoding="utf-8"), indent=2)
    print("wrote", p, flush=True)
    # quick agreement summary
    names = [n for n, _d, _r in ITEMS]
    ref = {n: r for n, _d, r in ITEMS}
    print("\nname                 ref " + " ".join("%-18s" % k for k in raters))
    for n in names:
        row = "%-20s %d  " % (n, ref[n]) + " ".join("%-18s" % str(raters[k].get(n)) for k in raters)
        print(row)
    # per-rater exact agreement with census ref
    print("\nper-rater exact agreement vs census ref:")
    for k in raters:
        ex = sum(1 for n in names if raters[k].get(n) == ref[n])
        print("  %-22s %d/%d" % (k, ex, len(names)))

if __name__ == "__main__":
    main()
