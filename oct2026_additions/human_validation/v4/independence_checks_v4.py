# -*- coding: utf-8 -*-
"""Follow-up on the score_v4.py warnings (PROTOCOL_v4.md, Section 4): are the three returned workbooks
independent of one another and of the logged LM raters?

Run after score_v4.py, from human_validation/v4/:  python independence_checks_v4.py
Writes independence_checks_v4.md. No user, account, or folder name is printed; only whether they are equal.

Checks:
1. Excel save fingerprints (workbook.xml): whether the save folder's user-profile name and the Excel build
   are the same across workbooks.
2. Field-by-field identity between raters (source, base bin, final bin, confidence, corrections, phrase).
3. Which excerpt sentence each rater quoted as deciding, mapped by token overlap, and the same for the
   logged LM raters in the excerpt-only condition (same excerpts): how often two independent readers
   choose the same sentence (LM runs of different models; reruns of one model), against the human pairs.
4. Human bins and quiz answers against the logged LM runs.
"""
from __future__ import annotations

import itertools
import json
import re
import statistics as st
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
HV = HERE.parent
RES = json.load(open(HERE / "result_v4.json", encoding="utf-8"))
W = RES["workbooks"]
R = sorted(W)
ITEMS = sorted(W[R[0]]["census"])
EX = json.load(open(HV / "llm_census_logged" / "excerpts.json", encoding="utf-8"))["items"]
LM_ROWS = [json.loads(l) for l in open(HV / "llm_census_logged" / "raw.jsonl", encoding="utf-8")]
STOP = set("the a an of to and in is are be by for from with that this it as on or its their we our which was were at".split())


def toks(s):
    return [t for t in re.findall(r"[a-z0-9]+", (s or "").lower()) if t not in STOP]


def norm(s):
    return " ".join(toks(s))


def sentences(i):
    out = []
    for e in EX[i]["excerpts"]:
        out += [s for s in re.split(r"(?<=[.!?])\s+(?=[A-Z(])", e["text"]) if len(s.split()) >= 4]
    return out


def deciding_sentence(i, phrase):
    p = set(toks(phrase))
    S = sentences(i)
    if not p or not S:
        return None
    k = max(range(len(S)), key=lambda j: (len(p & set(toks(S[j]))) / len(p), -j))
    return k if len(p & set(toks(S[k]))) / len(p) >= 0.5 else None


def same(a, b):
    its = [i for i in ITEMS if a.get(i) is not None and b.get(i) is not None]
    return sum(a[i] == b[i] for i in its), len(its)


def main():
    L = ["# v4 independence checks (generated by independence_checks_v4.py)", ""]
    # 1. save fingerprints
    fp = {}
    for c in R:
        z = zipfile.ZipFile(HERE / "returned" / W[c]["file"])
        wbx = z.read("xl/workbook.xml").decode("utf-8", "replace")
        ap = re.search(r'absPath url="([^"]*)"', wbx)
        prof = re.match(r"[A-Za-z]:\\Users\\([^\\]+)\\", ap.group(1)) if ap else None
        build = re.search(r'rupBuild="(\d+)"', wbx)
        fp[c] = {"profile": prof.group(1) if prof else None, "build": build.group(1) if build else None,
                 "office_user": W[c]["integrity"]["docprops_returned"]["core"].get("lastModifiedBy"),
                 "modified": W[c]["integrity"]["docprops_returned"]["core"].get("modified")}
    eq = lambda k: len({fp[c][k] for c in R}) == 1
    L += ["## 1. Save fingerprints", "",
          f"- Office user name (lastModifiedBy) equal across workbooks: {eq('office_user')}",
          f"- user-profile name of the save folder equal across workbooks: {eq('profile')}",
          f"- Excel build equal across workbooks: {eq('build')} (build {fp[R[0]]['build']})",
          "- last saved (UTC): " + ", ".join(f"{c} {fp[c]['modified']}" for c in R), "",
          "Coordinator follow-up (2026-10-01): each rater filled the workbook on a separate computer in one lab, whose "
          "installations share one user name; the workbooks were sent and returned through a messenger, which sets the "
          "file-system times on receipt. The document-internal save times above differ by rater.", ""]
    # 2. field identity
    L += ["## 2. Rows identical between raters (of 29)", "", "| pair | source | base | final | confidence | corrections | deciding phrase (normalized text) |",
          "|---|---:|---:|---:|---:|---:|---:|"]
    for a, b in itertools.combinations(R, 2):
        A, B = W[a]["census"], W[b]["census"]
        cnt = [sum(A[i][f] == B[i][f] for i in ITEMS) for f in ("source", "base", "final", "confidence")]
        cnt += [sum(norm(A[i][f]) == norm(B[i][f]) for i in ITEMS) for f in ("corrections", "phrase")]
        L.append(f"| {a}-{b} | " + " | ".join(map(str, cnt)) + " |")
    verbatim = {c: sum(any(norm(W[c]["census"][i]["phrase"]) == norm(e["text"]) or norm(W[c]["census"][i]["phrase"]) in norm(e["text"])
                           for e in EX[i]["excerpts"]) for i in ITEMS) for c in R}
    L += ["", "Deciding phrases quoted verbatim from an excerpt: " + ", ".join(f"{c} {verbatim[c]}/29" for c in R), ""]
    # 3. deciding sentence
    human = {c: {i: deciding_sentence(i, W[c]["census"][i]["phrase"]) for i in ITEMS} for c in R}
    lm = defaultdict(dict)
    for r in LM_ROWS:
        if r["stage"] == "partA" and r["condition"] == "B" and r.get("parsed", {}).get("ok") and r["item_id"] in ITEMS:
            lm[(r["model"], r["run"])][r["item_id"]] = deciding_sentence(r["item_id"], r["parsed"].get("key_phrase"))
    cross, rerun = [], []
    for a, b in itertools.combinations(sorted(lm), 2):
        s, n = same(lm[a], lm[b])
        (rerun if a[0] == b[0] else cross).append(s / n)
    L += ["## 3. Same deciding sentence", "", "| pair | same sentence / items mapped for both |", "|---|---|"]
    for a, b in itertools.combinations(R, 2):
        s, n = same(human[a], human[b])
        L.append(f"| {a}-{b} | {s}/{n} ({s / n:.3f}) |")
    L += ["", f"Logged LM raters, excerpt-only condition: pairs of runs of different models: mean {st.mean(cross):.3f} "
          f"(range {min(cross):.3f}-{max(cross):.3f}, {len(cross)} pairs); pairs of reruns of one model: mean {st.mean(rerun):.3f} "
          f"(range {min(rerun):.3f}-{max(rerun):.3f}, {len(rerun)} pairs).",
          "Each human against the LM runs: " + "; ".join(
              f"{c} mean {st.mean(same(human[c], lm[k])[0] / max(1, same(human[c], lm[k])[1]) for k in lm):.3f}" for c in R),
          f"Phrases not mapped to a sentence (overlap < 0.5): " + ", ".join(f"{c} {sum(v is None for v in human[c].values())}" for c in R), ""]
    # 4. bins and quiz vs LM runs
    runs = defaultdict(dict)
    for r in LM_ROWS:
        if r["stage"] == "partA" and r.get("parsed", {}).get("ok"):
            p = r["parsed"]
            runs[(r["model"], r["condition"], r["run"])][r["item_id"]] = (p["source"], p["base"], p["final"])
    L += ["## 4. Against the logged LM runs", ""]
    for c in R:
        t = {i: (W[c]["census"][i]["source"], W[c]["census"][i]["base"], W[c]["census"][i]["final"]) for i in ITEMS}
        best = max((sum(run.get(i) == t[i] for i in ITEMS), "/".join(map(str, k))) for k, run in runs.items())
        L.append(f"- {c}: most rows identical to any single LM run (source, base, final): {best[0]}/29 ({best[1]})")
    for i in ("TWOWIKI_ANSWER", "GRB_ANSWER"):
        cnt = Counter(v[i] for v in runs.values() if i in v)
        L.append(f"- {i}: humans {[(W[c]['census'][i]['source'], W[c]['census'][i]['base'], W[c]['census'][i]['final']) for c in R]}; LM runs {dict(cnt)}")
    lmq = defaultdict(Counter)
    for r in LM_ROWS:
        if r["stage"] == "quiz" and r.get("parsed", {}).get("ok"):
            lmq[r["item_id"]][(r["parsed"]["final"], r["parsed"]["source"])] += 1
    L += ["", "Quiz (final bin, source): key / each human / LM runs:"]
    for q in sorted(W[R[0]]["quiz"]["items"]):
        x = W[R[0]]["quiz"]["items"][q]
        L.append(f"- {q}: key ({x['key']}, {x['key_source']}); humans " +
                 ", ".join(f"{c} ({W[c]['quiz']['items'][q]['final']}, {W[c]['quiz']['items'][q]['source']})" for c in R) +
                 f"; LM runs {dict(lmq[q])}")
    (HERE / "independence_checks_v4.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
