def style_header(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[chr(64 + i) if i <= 26 else "A" + chr(64 + i - 26)].width = w
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="DDEBF7")
        c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "A2"


def wrap_rows(ws):
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")


def add_dv(ws, col, formula, n_rows, prompt):
    dv = DataValidation(type="list", formula1=formula, allow_blank=True, showDropDown=False)
    dv.prompt = prompt
    dv.error = "Choose a value from the list."
    ws.add_data_validation(dv)
    dv.add(f"{col}2:{col}{n_rows + 1}")


def info_sheet(wb, title_rows):
    ws = wb.create_sheet("Rater_info", 0)
    ws.append(["field", "your answer"])
    for r in title_rows:
        ws.append([r, ""])
    style_header(ws, [58, 50])
    wrap_rows(ws)


